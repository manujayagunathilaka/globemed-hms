package lk.jiat.oodp.globemed.hms.gui.components;

import java.awt.Color;
import java.awt.Component;
import java.awt.Graphics;
import java.awt.Graphics2D;
import java.awt.Insets;
import java.awt.RenderingHints;
import javax.swing.border.AbstractBorder;

/**
 *
 * @author Manujaya
 */
public class RightRoundedBorder extends AbstractBorder {

    private Color color;
    private int radius;

    public RightRoundedBorder(Color color, int radius) {
        this.color = color;
        this.radius = radius;
    }

    @Override
    public void paintBorder(Component c, Graphics g, int x, int y, int width, int height) {
        super.paintBorder(c, g, x, y, width, height);
        Graphics2D g2d = (Graphics2D) g;
        g2d.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
        g2d.setColor(this.color);

        g2d.fillRoundRect(x, y, width, height, radius * 2, radius * 2);
        g2d.fillRect(x, y, width - radius, height);
        
        g2d.dispose();
    }

    @Override
    public Insets getBorderInsets(Component c) {
        return new Insets(4, 8, 4, 8);
    }

    @Override
    public Insets getBorderInsets(Component c, Insets insets) {
        insets.left = 8;
        insets.right = 8;
        insets.top = 4;
        insets.bottom = 4;
        return insets;
    }
}
