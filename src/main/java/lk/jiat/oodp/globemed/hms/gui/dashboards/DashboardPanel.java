    private void loadDashboardByRole() {
        this.setLayout(new BorderLayout()); 
        this.removeAll(); 

        UserRole role = SessionManager.getInstance().getCurrentUserProfile().getUser().getUserRole();

        switch (role) {
            case ADMIN:
                add(new AdminDashboardPanel(), BorderLayout.CENTER);
                break;
            case DOCTOR:
                add(new JLabel("Welcome Doctor! Your Dashboard is under construction."), BorderLayout.CENTER);
                break;
            case NURSE:
                add(new JLabel("Welcome Nurse! Your Dashboard is under construction."), BorderLayout.CENTER);
                break;
            default:
//                add(new JLabel("Welcome ! Your Dashboard is under construction."), BorderLayout.CENTER);
                add(new AdminDashboardPanel(), BorderLayout.CENTER);
                break;
        }

        this.revalidate();
        this.repaint();
    }
    
