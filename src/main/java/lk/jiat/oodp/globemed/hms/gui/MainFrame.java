    private void applyRoleBasedVisibility(User currentUser) {

        boolean canAccessAppointments = permissionService.checkPermission(currentUser, AppPermission.ACCESS_APPOINTMENT_PANEL);
        btnNavAppoinment.setVisible(canAccessAppointments); 

        boolean canAccessBilling = permissionService.checkPermission(currentUser, AppPermission.ACCESS_BILLING_PANEL);
        btnNavBilling.setVisible(canAccessBilling); 

        boolean canAccessPermissions = permissionService.checkPermission(currentUser, AppPermission.ACCESS_PERMISSIONS_PANEL);
        btnNavBilling1.setVisible(canAccessPermissions);
        
        boolean canAccessSecurity = permissionService.checkPermission(currentUser, AppPermission.ACCESS_PERMISSIONS_PANEL);
        btnSecurity.setVisible(canAccessSecurity);
//        btnSecurity.setVisible(true);
        
        boolean canManageDoctors = permissionService.checkPermission(currentUser, AppPermission.ACCESS_DOCTOR_MANAGEMENT);
        btnDoctorManagement.setVisible(canManageDoctors);

    }
    
