    private void jLoInButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jLoInButtonActionPerformed
        // TODO add your handling code here:

        String username = jUsernameTextField.getText().trim();
        String password = new String(jPasswordField.getPassword());

        if (username.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter your username.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            jUsernameTextField.requestFocus();
            return;
        }
        if (password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter your password.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            jPasswordField.requestFocus();
            return;
        }

        Optional<User> userOpt = authService.login(username, password);

        if (userOpt.isPresent()) {
            User user = userOpt.get();
            System.out.println("Login successful for user: " + user.getUsername());

            boolean profileLoaded = SessionManager.getInstance().login(user);

            if (profileLoaded) {
                new MainFrame().setVisible(true);
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(this, "User profile data could not be found. Please contact an administrator.", "Login Error", JOptionPane.ERROR_MESSAGE);
            }

        } else {
            JOptionPane.showMessageDialog(this, "Invalid username or password. Please try again.", "Login Failed", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_jLoInButtonActionPerformed

